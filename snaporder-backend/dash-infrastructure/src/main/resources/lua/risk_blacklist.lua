-- 三类精确黑名单查询（一次往返）
--
-- 为什么必须用 Lua：严格说不是「必须」——三次 EXISTS 各自原子，分开调用也不会算出
-- 错的答案。合成一个脚本的唯一理由是**往返次数**：拆成三次 EVAL 就是三次网络往返，
-- 与蓝图 §3.8 的 10ms 总 deadline 直接冲突。三类查询之间没有任何依赖，
-- 合并进来是纯粹的净收益，不像 risk_cluster.lua 那样还兼有「读取-判断-写入」的原子性需求。
--
-- KEYS[1] = risk:bl:user:{userId}            用户黑名单
-- KEYS[2] = risk:bl:device:{deviceHash}      缺失时为占位键
-- KEYS[3] = risk:bl:ip:{ipHash}              缺失时为占位键
-- ARGV[1] = 是否存在设备维度：1=有 0=无（客户端没带设备标识）
-- ARGV[2] = 是否存在 IP 维度：1=有 0=无
-- 返回：{用户是否命中, 设备是否命中, IP 是否命中}，命中为 1，未命中为 0
--
-- ⚠ 用 EXISTS 而不是 GET。
--   黑名单的语义是「键存在即拉黑」，值是什么无所谓——EXISTS 正好表达这件事，
--   GET 还得把值读回来丢弃。更要紧的是类型：EXISTS 对**任何类型**的键都返回 1，
--   不做类型检查；GET 遇到非字符串类型的键会直接 WRONGTYPE 报错。
--   于是蓝图 §3.8 故障表里那条「键类型错误」**在黑名单维度不适用**——
--   运维误把黑名单键建成 Hash 或 List，EXISTS 照样答「在」，黑名单照样生效。
--   这条只适用于特征采集侧（SADD/ZADD 对错误类型会报错），别照着故障表去
--   构造「错类型键诱发黑名单降级」的测试：那条路径根本不存在，
--   RiskPreCheckIT 覆盖它只会得到一个永远通过的假用例。
--
-- ⚠ 占位键在这里比 risk_cluster.lua 更安全，但两个 if 仍然保留。
--   EXISTS 是只读命令，**不会创建键**；就算占位键漏进来被访问，也只是返回 0，
--   不会像那边漏进去就是真的 SADD/ZADD 建出一个键来。
--   保留 if 防的是另一件事：万一真有人在 Redis 里建了一个字面叫 risk:_absent_ 的
--   黑名单键，无守卫的写法会让它同时命中「设备」和「IP」两个维度。
--   也就是说这里的守卫不是安全防线，而是防「占位键这个名字被人占用」。
--
-- ⚠ TTL 由写入方决定，脚本不管。
--   永久封禁就不设 TTL，临时封禁就带 TTL——「黑名单失效后不再拦截」（蓝图 §3.5）
--   由 Redis 的过期语义天然满足，不需要应用侧判任何东西，也不需要在这里读 TTL。
--
-- ⚠ 缺失的设备/IP 维度不查、结果恒为 0，与端口契约一致。
--   它们对应的键本来就该不存在（键名带 HMAC 哈希，没有原始值根本构造不出来），
--   与「查了没命中」在返回值上同形——区分这两件事是调用方的事：
--   查询失败会抛异常并记 BLACKLIST_FAILED，本次三条全 0。

local hits = {0, 0, 0}

if redis.call('EXISTS', KEYS[1]) == 1 then
    hits[1] = 1
end

if ARGV[1] == '1' and redis.call('EXISTS', KEYS[2]) == 1 then
    hits[2] = 1
end

if ARGV[2] == '1' and redis.call('EXISTS', KEYS[3]) == 1 then
    hits[3] = 1
end

return hits
