package com.campusdash.domain.risk.model;

/**
 * 风控降级原因（P9.2 设计 §3.4）。
 *
 * <p><b>六个常量而不是一个布尔</b>：蓝图 §3.9 的事件聚合口径是「同一实例、
 * **同一原因** 10 秒最多 1 条」。没有原因就聚合不了——一个 {@code degraded=true}
 * 只能说明「出了问题」，运维既无法判断是黑名单还是特征采集挂了，也无法按原因限流。
 *
 * <p><b>降级的语义是「少一个证据」，不是「放行」</b>——这是蓝图 §3.8 那张表最容易被
 * 读错的地方。任何一种降级发生时，其余步骤照常执行，决策照常得出：
 *
 * <table border="1">
 *   <caption>降级与决策的关系</caption>
 *   <tr><th>情形</th><th>处理</th></tr>
 *   <tr><td>黑名单查询失败</td><td>该维度记 false，特征照采、决策照跑</td></tr>
 *   <tr><td>某次特征采集失败</td><td>该维度计数记 0，黑名单照查、决策照跑</td></tr>
 *   <tr><td>两者都失败</td><td>分数为 0 → {@code PASS}，但两个原因都记进本次决策</td></tr>
 * </table>
 *
 * <p>只有「所有证据都拿不到」时才**事实性地**退化成 {@code PASS}——那是分数为 0 的
 * 自然结果，不是一个写着「失败就放行」的分支。区别很实在：黑名单挂了但设备维度
 * 已经越线时，决策**仍然是 {@code BLOCK}**；写成 fail-open 分支就会漏掉它。
 *
 * <p><b>声明顺序即日志里 {@code degradeReasons} 的顺序</b>，理由同
 * {@link RiskRuleId}：顺序不稳定会让同一次决策产出不同文本，
 * 离线去重时会把它当成两条。
 */
public enum DegradeReason {

    /** {@code risk_user_window.lua} 调用失败（用户 10s/60s 窗口计数拿不到）。 */
    USER_WINDOW_FAILED,

    /** {@code risk_cluster.lua} 调用失败（设备与 IP 三个维度拿不到）。 */
    CLUSTER_FAILED,

    /** 黑名单查询失败（三类黑名单是否命中无从判断）。 */
    BLACKLIST_FAILED,

    /**
     * 限频键读取失败。**与「键不存在」是两回事**：读失败时无法判断该用户是否正在
     * 冷却期，只能当作「没有命中冷却」继续，代价是可能放过一个本该被限频的请求。
     * 这是必须记进原因里的信息，否则线上会表现为「限频偶尔失灵」而查不出所以然。
     */
    LIMIT_READ_FAILED,

    /**
     * 限频键写入失败。与读取失败方向相反：这一次的 {@code LIMIT} 决策是对的，
     * 但冷却期没能生效，后续请求不会被这条规则拦住——同样的用户会立刻再来一次。
     */
    LIMIT_WRITE_FAILED,

    /**
     * 预检的时间预算耗尽（P9.3 决策 D9）。
     *
     * <p>与上面五条**不是同类**：那五条都是某一次 Redis 调用失败了，这一条是
     * 「剩下的步骤不做了」——可能一条命令都没失败，只是前面几条加起来超出了预算。
     * 所以它也**不是「Redis 挂了」的同义词**：预算配得过小、甚至配成 0
     * （故障降级的纯配置触发方式，P9.3 决策 D11）同样会记这一条。
     *
     * <p>记了它就意味着**证据不全**：此后所有采集类端口一律没有再被调用。决策本身
     * 照常给出（降级不是放行），但若预算耗尽时决策仍是 {@code PASS}，
     * {@code fail-open=false} 下这次预检会被判为「不可用」而不是「放行」（决策 D7）。
     *
     * <p><b>必须追加在末尾</b>：声明序即日志里 {@code degradeReasons} 的顺序（见类注释），
     * 插在中间会让「声明序 = 离线去重用的稳定文本」这条前提在历史数据上失效。
     */
    DEADLINE_EXCEEDED
}
